SELECT t.base_table,
       t.base_table || '_' AS audit_table_name,
       t.expectation,
       CASE WHEN EXISTS (SELECT 1 FROM all_objects o WHERE o.object_name = t.base_table || '_')
            THEN 'FOUND' ELSE 'MISSING' END AS actual_result
FROM (
  SELECT 'AP_INVOICES_ALL' AS base_table, 'Expected FOUND' AS expectation FROM dual
  UNION ALL SELECT 'AP_INVOICE_LINES_ALL', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'AP_INVOICE_DISTRIBUTIONS_ALL', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'AP_PAYMENT_SCHEDULES_ALL', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'GL_JE_BATCHES', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'GL_JE_HEADERS', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'GL_JE_LINES', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'FA_ADDITIONS_B', 'Expected FOUND' FROM dual
  UNION ALL SELECT 'FA_ADDITIONS_TL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'AP_CHECKS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'AP_HOLDS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'RA_CUSTOMER_TRX_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'RA_CUSTOMER_TRX_LINES_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'AR_CASH_RECEIPTS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'AR_RECEIVABLE_APPLICATIONS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'CE_STATEMENT_HEADERS', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'CE_STATEMENT_LINES', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'POR_REQUISITION_HEADERS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'POR_REQUISITION_LINES_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'PO_HEADERS_ALL', 'Expected MISSING' FROM dual
  UNION ALL SELECT 'PO_LINES_ALL', 'Expected MISSING' FROM dual
) t
ORDER BY t.expectation, t.base_table
;

